def interp(tab, v):
    if v <= tab[0][0]:
        return tab[0][1]
    for (v0, u0), (v1, u1) in zip(tab, tab[1:]):
        if v <= v1:
            return u0 + (u1 - u0) * (v - v0) / float(v1 - v0)
    return tab[-1][1]


def run_at(row, seed):
    """(u0, u1) of the mask run containing seed, or the nearest run."""
    xs = np.nonzero(row)[0]
    if xs.size == 0:
        return None
    cuts = np.nonzero(np.diff(xs) > 1)[0]
    starts = np.concatenate(([xs[0]], xs[cuts + 1]))
    ends = np.concatenate((xs[cuts], [xs[-1]]))
    best = min(range(len(starts)), key=lambda i: 0 if starts[i] <= seed <= ends[i]
               else min(abs(starts[i] - seed), abs(ends[i] - seed)))
    return int(starts[best]), int(ends[best])


def median5(vals):
    out = []
    for i in range(len(vals)):
        w = sorted(vals[max(0, i - 2):i + 3])
        out.append(w[len(w) // 2])
    return out


def main():
    m = np.asarray(Image.open(os.path.join(HERE, "ref", "REF_MASK.png")).convert("L")) > 127
    lines = ['"""AUTO-GENERATED by measure.py from ref/REF_MASK.png - do not edit. Rows (v, u_left, u_right) px."""']
    for name, (v0, v1, seed, cl, cr) in SCANS.items():
        rows = []
        for v in list(range(v0, v1, STEP)) + [v1]:
            row = m[v].copy()
            lo = int(round(interp(cl, v))) if cl else 0
            hi = int(round(interp(cr, v))) if cr else m.shape[1] - 1
            row[:lo] = False
            row[hi + 1:] = False
            r = run_at(row, min(max(interp(seed, v), lo), hi))
            if r and r[1] - r[0] >= 4:
                rows.append((v, r[0], r[1]))
        ul, ur = median5([r[1] for r in rows]), median5([r[2] for r in rows])
        rows = [(r[0], a, b) for r, a, b in zip(rows, ul, ur)]
        lines.append("%s = [%s]" % (name, ", ".join("(%d, %d, %d)" % r for r in rows)))
        print(name, len(rows), "rows", rows[0], rows[len(rows) // 2], rows[-1])
    with open(os.path.join(HERE, "measured.py"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
